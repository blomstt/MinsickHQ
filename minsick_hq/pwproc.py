"""A small PipeWire process of the app's own, running one generated config. The equaliser and the
microphone cleanup each run in one, so switching either off removes everything it added and
nothing is ever written to PipeWire's own configuration.
No Qt here: everything in this file can be tested from a terminal.
"""
import os
import shutil
import subprocess
import tempfile

# Every config starts with the same few modules, from PipeWire's own filter-chain.conf
BASE_CONFIG = """context.properties = {
    log.level = 0
}
context.spa-libs = {
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}
"""
BASE_MODULES = """    { name = libpipewire-module-rt
        args = { }
        flags = [ ifexists nofail ]
    }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
"""


def config(module_text, title):
    """A whole config: the base modules plus one module of ours."""
    return (f"# Generated by Minsick HQ ({title}). Changes here are overwritten; use the app instead\n"
            + BASE_CONFIG + "context.modules = [\n" + BASE_MODULES + module_text + "]\n")


def available():
    """True when the pipewire and pw-cli commands are installed."""
    return shutil.which("pipewire") is not None and shutil.which("pw-cli") is not None


class PipeWireProcess:
    def __init__(self, name, runner=subprocess):
        self.name = name
        self.runner = runner
        self.process = None
        self.folder = tempfile.mkdtemp(prefix=f"minsick-hq-{name}-")

    def running(self):
        return self.process is not None and self.process.poll() is None

    def start(self, text):
        self.stop()
        path = os.path.join(self.folder, f"{self.name}.conf")
        with open(path, "w") as file:
            file.write(text)
        self.process = self.runner.Popen(["pipewire", "-c", path], stdout=subprocess.DEVNULL,
                                         stderr=subprocess.DEVNULL)

    def stop(self):
        if self.process is not None:
            if self.process.poll() is None:
                self.process.terminate()
                try:
                    self.process.wait(timeout=3)
                except subprocess.TimeoutExpired:
                    self.process.kill()
            self.process = None
